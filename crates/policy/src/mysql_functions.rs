pub(crate) fn is_known_pure_function(name: &str) -> bool {
    PURE_FUNCTIONS.contains(&name.to_ascii_uppercase().as_str())
}

#[cfg(test)]
mod tests {
    use super::is_known_pure_function;

    #[test]
    fn common_read_functions_are_allowlisted() {
        for name in ["COUNT", "CONCAT", "JSON_EXTRACT", "NOW", "ROW_NUMBER"] {
            assert!(is_known_pure_function(name), "{name}");
        }
    }

    #[test]
    fn custom_functions_are_not_allowlisted() {
        assert!(!is_known_pure_function("change_read_only_mode"));
    }
}
